"""The data model shared by readers, writers, scorers and reports."""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from enum import Enum

RawFields = list[tuple[str, str]]
"""Source fields of a record as (field name, value) pairs, in the order of the input file."""


class Decision(str, Enum):
    """Pre-screening decision for one record.

    ``INCLUDE`` and ``UNCERTAIN`` records both go to human screening; ``EXCLUDE`` records
    scored below the calibrated threshold.
    """

    INCLUDE = "include"
    UNCERTAIN = "uncertain"
    EXCLUDE = "exclude"

    def __str__(self) -> str:
        return self.value


def sigmoid(x: float) -> float:
    """Return the logistic function of ``x`` without overflow for large magnitudes."""
    if x >= 0:
        return 1.0 / (1.0 + math.exp(-x))
    z = math.exp(x)
    return z / (1.0 + z)


@dataclass(frozen=True)
class Assessment:
    """The screener's output for one record.

    Attributes:
        score: logit(Yes) - logit(No) of the first answer token. Higher means more likely
            to be relevant.
        decision: The pre-screening decision derived from the score and the thresholds.
        reason: An optional one-line explanation generated by the model.
    """

    score: float
    decision: Decision
    reason: str | None = None

    @property
    def p_include(self) -> float:
        """The model's probability of answering Yes rather than No: sigmoid(score)."""
        return sigmoid(self.score)


@dataclass
class Record:
    """One bibliographic record: the unit that is screened.

    Attributes:
        id: Identifier that is unique within the input file. Readers take it from the
            source (for example the RIS ``ID`` tag, the PubMed PMID or an id column) and
            fall back to the 1-based position of the record in the file.
        title: Article title.
        abstract: Abstract text, empty when the source has none.
        authors: Author names as written in the source.
        year: Publication year, if it could be parsed.
        journal: Journal or source title.
        doi: Normalized DOI (lower case, without a ``https://doi.org/`` prefix).
        pmid: PubMed identifier.
        raw: All source fields as (field name, value) pairs, used to write the record back
            in its original format.
        label: Existing human decision: True for include, False for exclude, None when the
            record has not been screened by people yet.
        assessment: The screener's output, set after scoring.
    """

    id: str
    title: str = ""
    abstract: str = ""
    authors: list[str] = field(default_factory=list)
    year: int | None = None
    journal: str = ""
    doi: str = ""
    pmid: str = ""
    raw: RawFields = field(default_factory=list)
    label: bool | None = None
    assessment: Assessment | None = None

    def raw_values(self, name: str) -> list[str]:
        """Return every raw value stored under ``name``, in file order."""
        return [value for key, value in self.raw if key == name]

    def raw_value(self, name: str, default: str = "") -> str:
        """Return the first raw value stored under ``name``, or ``default``."""
        for key, value in self.raw:
            if key == name:
                return value
        return default
